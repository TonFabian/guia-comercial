export function LoginField({ icon, right, ...inputProps }: LoginFieldProps) {
  const [focused, setFocused] = useState(false);

  return (
    <div
      className={`flex h-[52px] items-center gap-3 rounded-[14px] border px-4 transition-colors ${
        focused ? 'border-[#F1A80A]' : 'border-[#2A2A2A]'
      }`}
      style={{ backgroundColor: LoginColors.input }}
    >
      <span className="shrink-0" style={{ color: LoginColors.muted }}>
        {ICONS[icon]}
      </span>
      <input
        {...inputProps}
        className="flex-1 bg-transparent text-base text-white outline-none placeholder:text-[#9CA3AF]"
        style={{ color: LoginColors.text }}
        onFocus={(event) => {
          setFocused(true);
          inputProps.onFocus?.(event);
        }}
        onBlur={(event) => {
          setFocused(false);
          inputProps.onBlur?.(event);
        }}
      />
      {right}
    </div>
  );
}
